  const LANGS = ["fr", "en", "es", "de"];
  const THEMES = ["amber", "ink", "ocean", "forest", "paper", "daylight"];

  function getLang() {
    let stored = "";
    try {
      stored = localStorage.getItem("galerie-lang") || "";
    } catch (err) {
      stored = "";
    }
    if (LANGS.indexOf(stored) >= 0) return stored;
    const nav = (navigator.language || "fr").slice(0, 2).toLowerCase();
    return LANGS.indexOf(nav) >= 0 ? nav : "fr";
  }

  function setLang(lang) {
    const next = LANGS.indexOf(lang) >= 0 ? lang : "fr";
    document.documentElement.lang = next;
    try {
      localStorage.setItem("galerie-lang", next);
    } catch (err) {
      /* sans effet */
    }
    return next;
  }

  function getTheme() {
    let stored = "";
    try {
      stored = localStorage.getItem("galerie-theme") || "";
    } catch (err) {
      stored = "";
    }
    if (THEMES.indexOf(stored) >= 0) return stored;
    const attr = document.documentElement.getAttribute("data-theme") || "";
    return THEMES.indexOf(attr) >= 0 ? attr : "amber";
  }

  function setTheme(theme) {
    const next = THEMES.indexOf(theme) >= 0 ? theme : "amber";
    document.documentElement.setAttribute("data-theme", next);
    try {
      localStorage.setItem("galerie-theme", next);
    } catch (err) {
      /* sans effet */
    }
    return next;
  }

  function t(key) {
    const lang = getLang();
    const pack = STR[lang] || STR.fr;
    if (Object.prototype.hasOwnProperty.call(pack, key)) return pack[key];
    if (Object.prototype.hasOwnProperty.call(STR.fr, key)) return STR.fr[key];
    return key;
  }

  function apply(root) {
    const scope = root || document;
    document.documentElement.lang = getLang();
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const text = t(el.getAttribute("data-i18n"));
      if (el.children.length) {
        const node = Array.prototype.find.call(el.childNodes, (n) => {
          return n.nodeType === 3 && n.textContent.trim();
        });
        if (node) node.textContent = text + " ";
      } else {
        el.textContent = text;
      }
    });
    scope.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
  }

  window.GalerieI18n = {
    t: t,
    apply: apply,
    getLang: getLang,
    setLang: setLang,
    getTheme: getTheme,
    setTheme: setTheme,
    LANGS: LANGS,
    THEMES: THEMES,
  };
